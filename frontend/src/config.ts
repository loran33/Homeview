/**
 * Pure Lovelace config model for the Homeview builder.
 *
 * Invariants:
 * - The loaded config is kept byte-identical to what Home Assistant returned,
 *   apart from the single view the builder edits. Views are never converted: a
 *   masonry view stays masonry, the builder only appends a `sections` view when
 *   the dashboard has none.
 * - Every operation is immutable and returns a new document, so Lit re-renders
 *   on reference change.
 * - Saved output always goes through `toSaveConfig`, a deep copy: no builder
 *   state can reach the dashboard.
 */

export type Columns = number | "full";
export type Rows = number | "auto";

export const MAX_COLUMNS = 12;
export const MIN_COLUMNS = 1;

export interface CardGridOptions {
  columns?: Columns;
  rows?: Rows;
}

/** A partial grid change coming from the inspector. */
export interface GridPatch {
  columns?: Columns;
  rows?: Rows;
}

export interface CardConfig {
  type: string;
  grid_options?: CardGridOptions;
  [key: string]: unknown;
}

export interface SectionConfig {
  type?: string;
  cards?: CardConfig[];
  [key: string]: unknown;
}

export interface ViewConfig {
  type?: string;
  title?: string;
  path?: string;
  max_columns?: number;
  sections?: SectionConfig[];
  [key: string]: unknown;
}

export interface LovelaceConfig {
  title?: string;
  views?: ViewConfig[];
  strategy?: { type?: string; [key: string]: unknown };
  [key: string]: unknown;
}

export interface Position {
  section: number;
  index: number;
}

export interface BuilderDocument {
  config: LovelaceConfig;
  viewIndex: number;
  /** True when the edited view was appended because the dashboard had none. */
  createdView: boolean;
}

function clone<T>(value: T): T {
  return typeof structuredClone === "function"
    ? structuredClone(value)
    : (JSON.parse(JSON.stringify(value)) as T);
}

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, Math.round(value)));
}

export function viewsOf(config: LovelaceConfig | undefined): ViewConfig[] {
  return config && Array.isArray(config.views) ? config.views : [];
}

export function sectionsOf(view: ViewConfig | undefined): SectionConfig[] {
  return view && Array.isArray(view.sections) ? view.sections : [];
}

export function cardsOf(section: SectionConfig | undefined): CardConfig[] {
  return section && Array.isArray(section.cards) ? section.cards : [];
}

export function findSectionsViewIndex(config: LovelaceConfig): number {
  return viewsOf(config).findIndex(
    (view) => view.type === "sections" && Array.isArray(view.sections),
  );
}

/**
 * A dashboard driven by a strategy is generated by code: writing to it without
 * the user taking control first is silently useless, so the builder refuses.
 */
export function isStrategyConfig(config: LovelaceConfig | undefined | null): boolean {
  if (!config) return false;
  if (config.strategy && typeof config.strategy === "object") return true;
  return viewsOf(config).some(
    (view) => view.strategy && typeof view.strategy === "object",
  );
}

/** New dashboards must carry a hyphen in `url_path`, or Home Assistant rejects them. */
export function slugify(value: string): string {
  const base = value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return base.includes("-") ? base : `${base || "view"}-view`;
}

export function openDocument(raw: unknown, viewTitle = "Homeview"): BuilderDocument {
  const config: LovelaceConfig =
    raw && typeof raw === "object" ? clone(raw as LovelaceConfig) : {};

  const existing = findSectionsViewIndex(config);
  if (existing >= 0) {
    return { config, viewIndex: existing, createdView: false };
  }

  const added: ViewConfig = {
    type: "sections",
    title: viewTitle,
    path: slugify(viewTitle),
    sections: [{ type: "grid", cards: [] }],
  };
  const views = viewsOf(config);
  return {
    config: { ...config, views: [...views, added] },
    viewIndex: views.length,
    createdView: true,
  };
}

export function targetView(doc: BuilderDocument): ViewConfig | undefined {
  return viewsOf(doc.config)[doc.viewIndex];
}

function withView(
  doc: BuilderDocument,
  update: (view: ViewConfig) => ViewConfig,
): BuilderDocument {
  const views = viewsOf(doc.config).map((view, index) =>
    index === doc.viewIndex ? update(view) : view,
  );
  return { ...doc, config: { ...doc.config, views } };
}

function withSectionCards(
  doc: BuilderDocument,
  sectionIndex: number,
  update: (cards: CardConfig[]) => CardConfig[],
): BuilderDocument {
  return withView(doc, (view) => {
    const sections = sectionsOf(view);
    const section = sections[sectionIndex];
    if (!section) return view;
    const cards = update(cardsOf(section));
    return {
      ...view,
      sections: sections.map((current, index) =>
        index === sectionIndex ? { ...current, cards } : current,
      ),
    };
  });
}

export function cardAt(
  doc: BuilderDocument,
  position: Position,
): CardConfig | undefined {
  return cardsOf(sectionsOf(targetView(doc))[position.section])[position.index];
}

export function insertCard(
  doc: BuilderDocument,
  position: Position,
  card: CardConfig,
): BuilderDocument {
  return withSectionCards(doc, position.section, (cards) => {
    const at = clamp(position.index, 0, cards.length);
    return [...cards.slice(0, at), card, ...cards.slice(at)];
  });
}

export function removeCard(
  doc: BuilderDocument,
  position: Position,
): BuilderDocument {
  return withSectionCards(doc, position.section, (cards) =>
    cards.filter((_, index) => index !== position.index),
  );
}

/**
 * Move a card to `to`. Within one section, a forward move removes the card
 * first, so the target index shifts down by one — adjusting here keeps
 * "drop after the next card" meaning what the user saw.
 */
export function moveCard(
  doc: BuilderDocument,
  from: Position,
  to: Position,
): BuilderDocument {
  const card = cardAt(doc, from);
  if (!card) return doc;
  const sameSection = from.section === to.section;
  if (sameSection && from.index === to.index) return doc;

  const removed = removeCard(doc, from);
  const index = sameSection && to.index > from.index ? to.index - 1 : to.index;
  return insertCard(removed, { section: to.section, index }, card);
}

export function updateCard(
  doc: BuilderDocument,
  position: Position,
  update: (card: CardConfig) => CardConfig,
): BuilderDocument {
  return withSectionCards(doc, position.section, (cards) =>
    cards.map((card, index) => (index === position.index ? update(card) : card)),
  );
}

export function normalizeColumns(value: unknown): Columns | undefined {
  if (value === "full") return "full";
  const parsed = typeof value === "number" ? value : Number(value);
  if (!Number.isFinite(parsed)) return undefined;
  return clamp(parsed, MIN_COLUMNS, MAX_COLUMNS);
}

export function normalizeRows(value: unknown): Rows | undefined {
  if (value === "auto") return "auto";
  const parsed = typeof value === "number" ? value : Number(value);
  if (!Number.isFinite(parsed) || parsed < 1) return undefined;
  return Math.round(parsed);
}

export function setCardGrid(
  doc: BuilderDocument,
  position: Position,
  patch: CardGridOptions,
): BuilderDocument {
  const columns =
    patch.columns === undefined ? undefined : normalizeColumns(patch.columns);
  const rows = patch.rows === undefined ? undefined : normalizeRows(patch.rows);

  return updateCard(doc, position, (card) => {
    const gridOptions: CardGridOptions = { ...(card.grid_options ?? {}) };
    if (columns !== undefined) gridOptions.columns = columns;
    if (rows !== undefined) gridOptions.rows = rows;
    return { ...card, grid_options: gridOptions };
  });
}

export function cardColumns(card: CardConfig): Columns {
  return card.grid_options?.columns ?? MAX_COLUMNS;
}

export function cardRows(card: CardConfig): Rows {
  return card.grid_options?.rows ?? "auto";
}

export function addSection(doc: BuilderDocument): BuilderDocument {
  return withView(doc, (view) => ({
    ...view,
    sections: [...sectionsOf(view), { type: "grid", cards: [] }],
  }));
}

/** Keeps at least one section: an empty sections view renders nothing. */
export function removeSection(
  doc: BuilderDocument,
  sectionIndex: number,
): BuilderDocument {
  return withView(doc, (view) => {
    const sections = sectionsOf(view);
    if (sections.length <= 1) return view;
    return {
      ...view,
      sections: sections.filter((_, index) => index !== sectionIndex),
    };
  });
}

export function toSaveConfig(doc: BuilderDocument): LovelaceConfig {
  return clone(doc.config);
}

export function cardDisplayName(card: CardConfig): string {
  for (const key of ["name", "heading", "title", "entity", "content"]) {
    const value = card[key];
    if (typeof value === "string" && value.trim() !== "") return value.trim();
  }
  return card.type.replace(/^custom:/, "");
}
